#!/usr/bin/env python
"""Numerical validation: analytic limits, convergence, residuals.  Writes results/tables/validation_summary.csv and
results/logs/validation_report.md.  Exit status is non-zero if any check fails."""
from __future__ import annotations

import csv
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np  # noqa: E402

from cosmic_evolution import FLRWBackground  # noqa: E402
from cosmic_evolution import units  # noqa: E402
from cosmic_evolution.background import cosmic_time as ct  # noqa: E402
from cosmic_evolution.config import CosmologyParams  # noqa: E402
from cosmic_evolution.early_universe import inflation as inf, recombination as rc  # noqa: E402
from cosmic_evolution.future import dark_energy_scenarios as des  # noqa: E402
from cosmic_evolution.geometry import flrw, horizons  # noqa: E402
from cosmic_evolution.numerics import convergence as cv  # noqa: E402
from cosmic_evolution.perturbations import growth_factor as gf, scalar_modes as sm  # noqa: E402

NO_RAD = dict(T_cmb=1e-2, N_eff=0.0, omega_b_h2=0.0)


def nr(**kw):
    return FLRWBackground(CosmologyParams(**{**NO_RAD, **kw}))


def checks():
    out = []

    def add(name, computed, reference, tol, note=""):
        err = abs(computed - reference) / abs(reference) if reference else abs(computed)
        out.append((name, computed, reference, err, tol, err <= tol, note))

    eds = nr(omega_m=1.0, omega_de=0.0, omega_k=0.0)
    add("EdS age (H0 t0 = 2/3)", ct.time_dimensionless(eds, 1.0), 2 / 3, 1e-9)
    lc = nr(omega_m=0.3, omega_de=0.7, omega_k=0.0)
    add("flat LCDM age vs closed form", ct.time_dimensionless(lc, 1.0), 2 / (3 * math.sqrt(0.7)) * math.asinh(math.sqrt(0.7 / 0.3)), 1e-9)
    add("Milne age (H0 t0 = 1)", ct.time_dimensionless(nr(omega_m=0.0, omega_de=0.0), 1.0), 1.0, 1e-9)
    dh = units.hubble_distance_Mpc(eds.H0)
    add("EdS comoving distance z=3", flrw.comoving_distance_mpc(eds, 3.0), 2 * dh * (1 - 0.5), 1e-9)
    add("EdS particle horizon", horizons.particle_horizon_mpc(eds), 2 * dh, 1e-9)
    ds = nr(omega_m=0.0, omega_de=1.0, omega_k=0.0)
    add("de Sitter event horizon", horizons.event_horizon_mpc(ds), dh, 1e-7)
    cl = nr(omega_m=2.0, omega_de=0.0)
    add("closed matter universe crunch time (2 pi / H0)", des.classify_fate(cl)["t_end_gyr"] / ct.hubble_time_gyr(cl), 2 * math.pi, 1e-5)
    fid = FLRWBackground(CosmologyParams())
    sol = des.integrate_scale_factor_ode(fid, 0.5)
    dt = ct.time_dimensionless(fid, sol.sol(0.5)[0]) - ct.time_dimensionless(fid, 1.0)
    add("second-order ODE vs quadrature (dt = 0.5/H0)", dt, 0.5, 1e-8)
    g = gf.solve_growth(nr(omega_m=0.3, omega_de=0.7, omega_k=0.0), a_i=1e-4, n=200)
    add("growth ODE vs Heath integral (flat LCDM, a=1)", float(g.D(1.0)), gf.heath_integral_growth(nr(omega_m=0.3, omega_de=0.7, omega_k=0.0), 1.0), 1e-7)
    b = sm.ModeBackground.quasi_de_sitter(1e-4)
    k = sm.k_of_exit(b, 20.0)
    add("Mukhanov-Sasaki vs de Sitter P_R", sm.evolve_curvature_mode(b, k), sm.slow_roll_amplitude(b, 20.0), 1e-3)
    ref = ct.age_gyr(fid)
    for n in (321, 1281):
        add(f"Simpson age, N = {n} log-spaced points", cv.age_vs_grid(fid, [n], "simpson")[0], ref, 1e-6 if n == 321 else 1e-9)
    rec = rc.solve_recombination(fid)
    add("recombination 100 theta* vs Planck theta_MC (approximate model)", 100 * rec.theta_star, 1.0409, 1.5e-2,
        "model approximation, not a numerical error")
    return out


def main() -> int:
    rows = checks()
    tdir = ROOT / "results" / "tables"
    ldir = ROOT / "results" / "logs"
    tdir.mkdir(parents=True, exist_ok=True)
    ldir.mkdir(parents=True, exist_ok=True)
    with open(tdir / "validation_summary.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["check", "computed", "reference", "relative_error", "tolerance", "pass", "note"])
        for r in rows:
            w.writerow([r[0], f"{r[1]:.12g}", f"{r[2]:.12g}", f"{r[3]:.3e}", f"{r[4]:.1e}", r[5], r[6]])
    lines = ["# Numerical validation report (generated by scripts/validate_numerics.py)", "",
             "| Check | Computed | Reference | Relative error | Tolerance | Result |", "|---|---:|---:|---:|---:|---|"]
    for r in rows:
        lines.append(f"| {r[0]} | {r[1]:.10g} | {r[2]:.10g} | {r[3]:.2e} | {r[4]:.0e} | {'PASS' if r[5] else 'FAIL'} |")
    ok = all(r[5] for r in rows)
    lines += ["", f"Overall: {'all checks passed' if ok else 'FAILURES PRESENT'} ({sum(r[5] for r in rows)}/{len(rows)})."]
    (ldir / "validation_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
